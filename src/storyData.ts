export type Effect = "peace" | "gang" | "rough" | "build" | "trust";
export interface Answer {
  text: string;
  reply: string;
  next?: string;
  effect?: Effect;
  cost?: number;
  gate?: "trust" | "future" | "truce";
}
function a(
  text: string,
  reply: string,
  next?: string,
  effect?: Effect,
  cost?: number,
  gate?: Answer["gate"],
): Answer {
  return { text, reply, next, effect, cost, gate };
}
